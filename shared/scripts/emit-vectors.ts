const settings = [];
rngCall = 200;
for (const [key, value] of Object.entries(settingValues)) {
  const sealed = await sealSetting(key, value, (d, aad) => encryptionService.encryptFile(mk, d, aad));
  const plain = new TextDecoder().decode(await encryptionService.decryptFile(mk, Uint8Array.from(atob(sealed.ciphertext), c => c.charCodeAt(0)).buffer as ArrayBuffer, sealed.iv, settingAad(key)));
  assertEqual(JSON.parse(plain), value, `setting ${key}`);
  settings.push({ key, value, plaintext: JSON.stringify(value), aad: settingAad(key), sealed });
}
out.settingSource = settingSource;
out.settings = settings;

// --- Records ---------------------------------------------------------------------------------
async function recordVector(kind: string, id: string, record: unknown, key = mk, keyName = 'masterKey') {
  const { payload, iv } = await encryptionService.encryptRecord(key, kind, id, record);
  assertEqual(await encryptionService.decryptRecord(key, kind, id, payload, iv), record, `record ${kind}:${id}`);
  return { kind, id, key: keyName, record, plaintext: JSON.stringify(record), aad: `chronicles:finance:v1:${kind}:${id}`, payload, iv };
}
const doseUuid = '3f2a9c1e-8b4d-4e7f-9a12-5c6d7e8f9a0b';
rngCall = 300;
out.records = [
  await recordVector('topic', String(12), { name: 'Health', icon: '🩺' }),
  await recordVector('dose', `${doseUuid}|2026-11-25`, { medicationPostId: 88, scheduledTime: '08:00', status: 'taken', takenAt: '8:05 AM', asNeeded: false }),
  await recordVector('bills', '9b1deb4d-3b7d-4bad-9bdd-2b0d7b3dcb6d', { name: 'Electric', amount: 84.5, dueDay: 14, frequency: 'monthly', autopay: true, notes: null }),
  // Sealed under the old key during a re-key: opens with [new, old]
  await recordVector('bills', '1c6e5f2a-7d3b-4c9e-8f1a-2b3c4d5e6f70', { name: 'Water', amount: 31, dueDay: 2 }, oldMk, 'oldMasterKey'),
];

process.stdout.write(JSON.stringify(out, null, 2) + '\n');

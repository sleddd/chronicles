/**
 * Known-answer vectors for ports of the client-side crypto (the Smith app's
 * Swift port). Everything goes through the real functions in shared/src/crypto
 * (and the client's settingCipher when it loads), with fixed keys, passwords
 * and salts. The functions that pick their own IVs (encryptPost,
 * encryptRecord, encryptFile) get them from a deterministic stand-in for
 * crypto.getRandomValues, so the output is the same on every run.
 *
 *   npx tsx shared/scripts/emit-vectors.ts > vectors.json
 *
 * (from the repo root; set TSX_TSCONFIG_PATH=client/tsconfig.json so the
 * client's `@shared/*` imports resolve). Every vector is opened again with the
 * real decrypt functions before it is written.
 */

import {
  encryptionService,
  deriveKEK,
  wrapKey,
  encrypt,
  decrypt,
  deriveAuthSecret,
  normalizePassword,
  uint8ArrayToBase64,
  PBKDF2_ITERATIONS,
} from '../src/crypto/index.js';

// --- Deterministic randomness ------------------------------------------------
let rngCall = 0;
Object.defineProperty(globalThis.crypto, 'getRandomValues', {
  configurable: true,
  writable: true,
  value: <T extends ArrayBufferView | null>(array: T): T => {
    if (array) {
      const bytes = new Uint8Array(array.buffer, array.byteOffset, array.byteLength);
      rngCall++;
      for (let i = 0; i < bytes.length; i++) bytes[i] = (0xa0 + rngCall * 13 + i * 7) & 0xff;
    }
    return array;
  },
});

const seq = (n: number, start: number, step: number) => Uint8Array.from({ length: n }, (_, i) => (start + i * step) & 0xff);
const b64 = (bytes: Uint8Array) => uint8ArrayToBase64(bytes);
const hex = (bytes: Uint8Array) => Array.from(bytes, b => b.toString(16).padStart(2, '0')).join('');

async function importMK(raw: Uint8Array): Promise<CryptoKey> {
  return crypto.subtle.importKey('raw', raw, { name: 'AES-GCM', length: 256 }, true, ['encrypt', 'decrypt']);
}

function assertEqual(a: unknown, b: unknown, what: string) {
  if (JSON.stringify(a) !== JSON.stringify(b)) throw new Error(`Self-check failed: ${what}`);
}

// --- Settings: the real client sealSetting if it loads ---------------------------
type SealFn = (key: string, value: unknown, enc: (d: ArrayBuffer, aad?: string) => Promise<{ ciphertext: ArrayBuffer; iv: string }>) => Promise<{ ciphertext: string; iv: string; v?: 2 }>;
let sealSetting: SealFn;
let settingAad: (key: string) => string;
let settingSource: string;
try {
  const mod = await import('../../client/src/services/settingCipher.js');
  sealSetting = mod.sealSetting as SealFn;
  settingAad = mod.settingAad;
  settingSource = 'client/src/services/settingCipher.ts (imported)';
} catch (err) {
  // Same as settingCipher.ts sealSetting for a key outside ROLLBACK_GUARDED
  settingAad = (key: string) => `chronicles:setting:v2:${key}`;
  sealSetting = async (key, value, enc) => {
    const data = new TextEncoder().encode(JSON.stringify(value));
    const { ciphertext, iv } = await enc(data.buffer as ArrayBuffer, settingAad(key));
    return { ciphertext: uint8ArrayToBase64(new Uint8Array(ciphertext)), iv, v: 2 };
  };
  settingSource = `replica of settingCipher.ts sealSetting (import failed: ${err instanceof Error ? err.message.split('\n')[0] : err})`;
}

// --- Fixed inputs -----------------------------------------------------------------
const mkRaw = seq(32, 0x10, 7);
const oldMkRaw = seq(32, 0x80, 3);
const mk = await importMK(mkRaw);
const oldMk = await importMK(oldMkRaw);

const asciiPassword = 'correct horse battery staple';
// "Cafe" + combining acute (NFKC composes it) + the "ﬁ" ligature (NFKC -> "fi")
const unicodePassword = 'Café ﬁle 2026!';
if (normalizePassword(unicodePassword) === unicodePassword) throw new Error('unicode password must change under NFKC');
const email = '  Henry.Smith@Example.COM ';

const out: Record<string, unknown> = {
  note: 'Generated by chronicles/shared/scripts/emit-vectors.ts with the real Chronicles crypto. Deterministic: do not edit by hand.',
  masterKey: b64(mkRaw),
  oldMasterKey: b64(oldMkRaw),
};

// --- authSecret -------------------------------------------------------------------
out.authSecret = [
  { password: asciiPassword, email, asTyped: false, iterations: PBKDF2_ITERATIONS, secret: await deriveAuthSecret(asciiPassword, email) },
  { password: unicodePassword, email: 'henry@example.com', asTyped: false, iterations: PBKDF2_ITERATIONS, secret: await deriveAuthSecret(unicodePassword, 'henry@example.com') },
  { password: unicodePassword, email: 'henry@example.com', asTyped: true, iterations: PBKDF2_ITERATIONS, secret: await deriveAuthSecret(unicodePassword, 'henry@example.com', PBKDF2_ITERATIONS, { asTyped: true }) },
];

// --- Password wrap (kek-wrap) --------------------------------------------------------
const probe = await encrypt(mk, 'probe', { iv: seq(12, 0x01, 1) });
async function wrapVector(password: string, asTyped: boolean, salt: Uint8Array, iv: Uint8Array) {
  const kek = await deriveKEK(password, salt, PBKDF2_ITERATIONS, asTyped);
  const wrapped = new Uint8Array(await wrapKey(mk, kek, iv, 'kek-wrap'));
  const v = { password, asTyped, salt: b64(salt), iv: b64(iv), iterations: PBKDF2_ITERATIONS, wrapped: b64(wrapped) };
  const opened = await encryptionService.unwrapMasterKey(password, v.salt, v.wrapped, v.iv, v.iterations);
  assertEqual(await decrypt(opened, probe.ciphertext, probe.iv), 'probe', `unwrap ${password} asTyped=${asTyped}`);
  return v;
}
out.wrap = [
  await wrapVector(asciiPassword, false, seq(16, 0x30, 5), seq(12, 0x40, 9)),
  await wrapVector(unicodePassword, false, seq(16, 0x50, 11), seq(12, 0x60, 3)),
  // An account whose password was set before normalization: opens only through the as-typed fallback
  await wrapVector(unicodePassword, true, seq(16, 0x70, 13), seq(12, 0x90, 5)),
];

